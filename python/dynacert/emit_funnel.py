"""Lean emission for certified funnels (`funnel.py`): `Spec.lean` (with the horizon) and
`FunnelCert.lean` (link + `Dynacert.Nonlinear.FunnelCert` data + the final theorem).

The link proves, from rumoca's own `Equations`, that the tracking error
`z = x - x*(t)` (with `x*` a rational polynomial in time, `GNC.PolynomialOrder.value`) satisfies
the hypotheses of `FunnelCert.output_bound`:

* continuity and right derivatives of `z` (gnc's `value_derivative`);
* on segment `i`, while `z` is in the band, `ż = (Σⱼ wtⱼ Aᵢⱼ) z + B w`: the reference range on the
  segment by Bernstein coefficients, a rational `cos` enclosure, the mean-value `sin` gain, and
  `linear_combination` of the model equations with multipliers found here;
* the disturbance energy bound and `z(0) = 0`.
"""

from __future__ import annotations

from fractions import Fraction

import sympy as sp

from . import analysis as an
from . import emit_lti
from .funnel import ExactCert, FunnelProblem, bernstein, poly_coeffs
from .lean import header, ident, mat, q, sympy_to_lean, vec

GEN = "dynacert (funnel)"


def _qr(x) -> str:
    """A rational literal typed `ℝ`."""
    return f"({q(x)} : ℝ)"


def _list(cs) -> str:
    return "[" + ", ".join(q(c) for c in cs) + "]"


# --- Spec ----------------------------------------------------------------------------------------

def emit_spec(prob, fp: FunnelProblem) -> str:
    m, spec = prob.model, prob.spec
    ns = m.ns
    out = [f"import Certs.{ns}.Model", "", "/-!", f"# Specification for `{m.name}`", "",
           "GENERATED by `dynacert` from the model and its `__Dynacert` annotations only; the",
           "certificate method and its numbers do not affect this file. Read this file to know",
           "what the certificate proves.", "-/", "",
           "set_option linter.style.setOption false", "set_option linter.style.longLine false",
           "", f"namespace {ns}.Spec", "", f"open Set {ns}", ""]
    conds = " ∧ ".join(f"|(u t).{m.var(d).lean}| ≤ {_qr(b)}"
                       for d, b in zip(fp.w_names, fp.w_bounds))
    out += ["/-- Admissible disturbances: componentwise peak bounds. -/",
            "def Admissible (u : ℝ → Inputs) (T : ℝ) : Prop :=",
            f"  ∀ t ∈ Ico 0 T, {conds}", "",
            "/-- The horizon of the claim (`__Dynacert(horizon = …)`). -/",
            f"def horizon : ℝ := {q(fp.horizon)}", ""]
    k = len(spec.certify)
    concl = " ∧ ".join(f"|(y t).{m.var(nm).lean}| ≤ (b {i} : ℝ)" for i, nm in enumerate(spec.certify))
    out += ["/-- **The claim.** Every solution with the model's parameter values, admissible",
            "disturbances and the model's initial condition keeps the certified outputs within",
            "the bounds `b` up to the horizon. -/",
            f"def Claim (b : Fin {k} → ℚ) : Prop :=",
            "  ∀ (p : Params) (u : ℝ → Inputs) (x : ℝ → States) (y : ℝ → Algebraics) (T : ℝ),",
            "    p.Bound → IsSolutionOn p u x y T → Admissible u T → Initial p (x 0) →",
            f"    (∀ t ∈ Ico 0 T, t ≤ horizon → {concl})", "", f"end {ns}.Spec", ""]
    return "\n".join(out)


# --- helpers for the link ------------------------------------------------------------------------

def _poly_lean(cs, tname="t") -> str:
    terms = []
    for k, c in enumerate(cs):
        if c == 0:
            continue
        terms.append(f"{_qr(c)}" if k == 0 else f"{_qr(c)} * {tname} ^ {k}")
    return " + ".join(terms) if terms else "(0 : ℝ)"


def _deriv(cs):
    return [c * k for k, c in enumerate(cs)][1:] or [Fraction(0)]


def _gram(g) -> str:
    q0, q1, (L0, d0), (L1, d1) = g
    return (f"⟨{mat(q0)},\n      {mat(L0)},\n      {vec(d0)},\n"
            f"      {mat(q1)},\n      {mat(L1)},\n      {vec(d1)}⟩")


def link_plan(prob, fp: FunnelProblem):
    """How the generated proof rewrites rumoca's equations, and the multipliers that close each
    error component.

    Algebraic definitions `y = rhs` are processed in dependency order: their dependencies are
    rewritten into them; a nominal algebraic (the reference of a state) is then replaced by
    `GNC.PolynomialOrder.value ref_k t` everywhere (also inside `sin`), others by their closed form.
    After rewriting, every error component `zdot_i - (A₀ z + a κ z_k + B w)` is a combination with
    rational constants of the rewritten dynamic equations, the `sin` gain, and the polynomial
    facts `value ref_k t = P_k(t)`, `value ref_kd t = P_k'(t)`."""
    m = prob.model
    t = fp.t
    vals = {k: sp.nsimplify(v, rational=True) for k, v in m.param_values().items()}
    eqs = m.equations_flat()
    alg_syms = {v.symbol: v for v in m.algebraics}
    nominal_alg = {}                          # algebraic symbol -> state index
    for k_, nm in enumerate(fp.nominal_names):
        if nm is not None:
            nominal_alg[m.var(nm).symbol] = k_
    defs, dyn = {}, []
    for i, e in enumerate(eqs):
        if e.lhs in alg_syms and e.lhs not in defs:
            defs[e.lhs] = i
        else:
            dyn.append(i)
    # dependency order
    order, seen = [], set()
    def visit(y, stack=()):
        if y in seen:
            return
        if y in stack:
            raise ValueError("cyclic algebraic definitions")
        rhs = eqs[defs[y]].rhs
        for dep in rhs.free_symbols & set(defs):
            visit(dep, stack + (y,))
        seen.add(y); order.append(y)
    for y in defs:
        visit(y)
    V = {k_: sp.Symbol(f"V{k_}") for k_ in range(len(fp.xs))}
    D = {k_: sp.Symbol(f"D{k_}") for k_ in range(len(fp.xs))}
    closed = {}
    for y in order:
        if y in nominal_alg:
            closed[y] = V[nominal_alg[y]]
        else:
            closed[y] = sp.nsimplify(eqs[defs[y]].rhs.subs(vals), rational=True).subs(closed)
    # dynamic residuals with the algebraics substituted, sin atoms named
    kap = sp.Symbol("kappa")
    if len(fp.atoms) != 1:
        raise NotImplementedError("one sin nonlinearity per model for now")
    at = fp.atoms[0]
    xk = fp.xs[at.k]
    S1, S2 = sp.Symbol("S1"), sp.Symbol("S2")
    sins = {sp.sin(xk): S1, sp.sin(V[at.k]): S2}
    res, rnames = [], []
    for i in dyn:
        e = eqs[i]
        r = sp.nsimplify(sp.expand((e.lhs - e.rhs).subs(vals)), rational=True).subs(closed)
        res.append(sp.expand(r).subs(sins)); rnames.append(f"e{i}")
    for k_ in range(len(fp.xs)):
        if fp.nominal_names[k_] is not None:
            cs = poly_coeffs(fp.nominal[k_], t)
            P = sum(sp.Rational(c.numerator, c.denominator) * t ** j for j, c in enumerate(cs))
            res += [V[k_] - P, D[k_] - sp.diff(P, t)]
            rnames += [f"hv{k_}", f"hd{k_}"]
    res.append(S1 - S2 - kap * (xk - V[at.k])); rnames.append("hg0")
    mult = []
    n = len(fp.xs)
    for i in range(n):
        dx = m.der[m.states[i].name]
        zdot = dx - (D[i] if fp.nominal_names[i] is not None else 0)
        z = [fp.xs[k_] - (V[k_] if fp.nominal_names[k_] is not None else fp.nominal[k_])
             for k_ in range(n)]
        rhs = sum(sp.Rational(a.numerator, a.denominator) * zk for a, zk in zip(fp.A0[i], z))
        ai = at.a[i]
        rhs += sp.Rational(ai.numerator, ai.denominator) * kap * z[at.k]
        rhs += sum(sp.Rational(b.numerator, b.denominator) * w for b, w in zip(fp.B[i], fp.ws))
        mu = an.multipliers(res, sp.expand(zdot - rhs))
        mult.append([(rnames[e], cf) for e, cf in mu])
    return dict(order=order, defs=defs, dyn=dyn, nominal_alg=nominal_alg, mult=mult)


# --- Cert -----------------------------------------------------------------------------------------

def emit_cert(prob, fp: FunnelProblem, ec: ExactCert, debug: bool = False) -> str:
    """`debug` skips the Gram checks (`sorry`) to iterate on the proof quickly; never certify
    with it."""
    m = prob.model
    ns = m.ns
    n, mw = len(fp.xs), len(fp.ws)
    S, d, h = ec.S, ec.d, ec.h
    k = len(ec.As[0])
    p_rows = len(ec.rows)
    lean_src = (prob.lean_src if hasattr(prob, "lean_src") else "")
    lits = emit_lti.decimal_literals(lean_src)
    states = m.states
    st = [v.lean for v in states]

    out = [f"import Certs.{ns}.Spec", "import Dynacert.Nonlinear.FunnelLink", ""]
    out += header(f"Funnel certificate for `{m.name}`", GEN)
    out += ["set_option linter.style.setOption false", "set_option linter.style.longLine false",
            "set_option linter.unusedSimpArgs false", "set_option linter.unusedTactic false",
            "set_option linter.unreachableTactic false", "set_option linter.unusedVariables false",
            "set_option linter.flexible false", "set_option linter.style.show false",
            "set_option maxRecDepth 100000", "set_option maxHeartbeats 0", "",
            f"namespace {ns}.Funnel", "",
            f"open Matrix Set Dynacert Dynacert.Linear Dynacert.Nonlinear {ns}", ""]
    # reference polynomials
    out += ["/-! ### Reference `x*(t)` (polynomials in time) -/", ""]
    refs = {}
    for i, v in enumerate(states):
        if fp.nominal_names[i] is None:
            continue
        cs = poly_coeffs(fp.nominal[i], fp.t)
        csd = _deriv(cs)
        refs[i] = (cs, csd)
        out += [f"/-- `{v.name}*(t)` = `{fp.nominal_names[i]}`. -/",
                f"def ref{i} : List ℚ := {_list(cs)}",
                f"def ref{i}d : List ℚ := {_list(csd)}",
                f"theorem ref{i}_diff : GNC.Planning.PolynomialKernel.differentiate ref{i} = ref{i}d := by",
                "  decide +kernel",
                f"theorem ref{i}_val (t : ℝ) : GNC.PolynomialOrder.value ref{i} t = {_poly_lean(cs)} := by",
                f"  simp [GNC.PolynomialOrder.value, GNC.Planning.PolynomialKernel.evaluate, ref{i}]",
                "  ring",
                f"theorem ref{i}d_val (t : ℝ) : GNC.PolynomialOrder.value ref{i}d t = {_poly_lean(csd)} := by",
                f"  simp [GNC.PolynomialOrder.value, GNC.Planning.PolynomialKernel.evaluate, ref{i}d]",
                "  ring",
                f"theorem ref{i}_deriv (t : ℝ) : HasDerivAt (GNC.PolynomialOrder.value ref{i})",
                f"    (GNC.PolynomialOrder.value ref{i}d t) t := by",
                f"  have := GNC.PolynomialOrder.value_derivative ref{i} t",
                f"  rwa [ref{i}_diff] at this", ""]

    def zcomp(i, s="s", t="t"):
        if i in refs:
            return f"{s}.{st[i]} - GNC.PolynomialOrder.value ref{i} {t}"
        return f"{s}.{st[i]} - {_qr(Fraction(fp.nominal[i]))}"

    def dcomp(i, s="ds", t="t"):
        if i in refs:
            return f"{s}.{st[i]} - GNC.PolynomialOrder.value ref{i}d {t}"
        return f"{s}.{st[i]}"

    out += ["/-! ### Error coordinates `z = x - x*(t)` -/", "",
            f"noncomputable def zvec (s : States) (t : ℝ) : Fin {n} → ℝ :=",
            "  ![" + ", ".join(zcomp(i) for i in range(n)) + "]",
            f"noncomputable def zdot (ds : States) (t : ℝ) : Fin {n} → ℝ :=",
            "  ![" + ", ".join(dcomp(i) for i in range(n)) + "]",
            f"def dist (v : Inputs) : Fin {mw} → ℝ := ![" +
            ", ".join(f"v.{m.var(w).lean}" for w in fp.w_names) + "]", ""]

    # certificate data: shared data in FunnelBase, one module per segment (Gram data and its
    # kernel checks, so no single Lean process holds all of them), assembled here
    K0d, K1d = (d + 1) * (n + mw), d * (n + mw)
    K0b, K1b = (d + 1) * (n + 1), d * (n + 1)
    pre = ["import Dynacert.Nonlinear.FunnelLink", ""] + header(
        f"Funnel certificate data for `{m.name}`", GEN) + [
        "set_option linter.style.setOption false", "set_option linter.style.longLine false",
        "set_option maxRecDepth 100000", "set_option maxHeartbeats 0", "",
        f"namespace {ns}.Funnel", "", "open Matrix Dynacert Dynacert.Linear Dynacert.Nonlinear", ""]
    base = pre + [f"def h : ℚ := {q(h)}",
                  f"def Bm : Matrix (Fin {n}) (Fin {mw}) ℚ := {mat(fp.B)}",
                  f"def γ : Fin {mw} → ℚ := {vec(ec.gamma)}",
                  f"def β : ℚ := {q(ec.beta)}",
                  f"def rows : Fin {p_rows} → Fin {n} → ℚ := ![" +
                  ", ".join(vec(r) for r in ec.rows) + "]", "", f"end {ns}.Funnel", ""]
    modules = {"FunnelBase.lean": "\n".join(base)}
    for i in range(S):
        seg = [l.replace("import Dynacert.Nonlinear.FunnelLink", f"import Certs.{ns}.FunnelBase")
               for l in pre]
        seg += [f"def A_{i} : Fin {k} → Matrix (Fin {n}) (Fin {n}) ℚ :=",
                "  ![" + ",\n    ".join(mat(A) for A in ec.As[i]) + "]",
                f"def P_{i} : Fin {2 * d + 1} → Matrix (Fin {n}) (Fin {n}) ℚ :=",
                "  ![" + ",\n    ".join(mat(Pr) for Pr in ec.P[i]) + "]",
                f"def qs_{i} : Fin {p_rows} → ℚ := {vec(ec.q[i])}",
                f"def dissG_{i} : Fin {k} → GramData {K0d} {K1d} :=",
                "  ![" + ",\n    ".join(_gram(g) for g in ec.diss[i]) + "]",
                f"def bandG_{i} : Fin {p_rows} → GramData {K0b} {K1b} :=",
                "  ![" + ",\n    ".join(_gram(g) for g in ec.band[i]) + "]", "",
                f"theorem dissOK_{i} : ∀ j, (dissG_{i} j).Valid {d} finSumFinEquiv",
                f"    (dissCoeff (coeffs P_{i}) (A_{i} j) Bm h γ) := " +
                ("sorry" if debug else "by decide +kernel"),
                f"theorem bandOK_{i} : ∀ l, (bandG_{i} l).Valid {d} finSumFinEquiv",
                f"    (bandCoeff (coeffs P_{i}) (rows l) (qs_{i} l)) := " +
                ("sorry" if debug else "by decide +kernel"), "", f"end {ns}.Funnel", ""]
        modules[f"FunnelSeg{i}.lean"] = "\n".join(seg)
    out[0:1] = [f"import Certs.{ns}.Spec"] + [f"import Certs.{ns}.FunnelSeg{i}" for i in range(S)]
    out += ["/-! ### Certificate (data and checks in `FunnelSeg*`) -/", "",
            f"def Aseg : Fin {S} → Fin {k} → Matrix (Fin {n}) (Fin {n}) ℚ := ![" +
            ", ".join(f"A_{i}" for i in range(S)) + "]",
            f"def Pseg : Fin {S} → Fin {2 * d + 1} → Matrix (Fin {n}) (Fin {n}) ℚ := ![" +
            ", ".join(f"P_{i}" for i in range(S)) + "]",
            f"def qs : Fin {S} → Fin {p_rows} → ℚ := ![" + ", ".join(f"qs_{i}" for i in range(S)) + "]",
            f"def ρs : Fin {S} → Fin {p_rows} → ℚ := ![" + ", ".join(vec(r) for r in ec.rho) + "]",
            f"def dissG : Fin {S} → Fin {k} → GramData {K0d} {K1d} := ![" +
            ", ".join(f"dissG_{i}" for i in range(S)) + "]",
            f"def bandG : Fin {S} → Fin {p_rows} → GramData {K0b} {K1b} := ![" +
            ", ".join(f"bandG_{i}" for i in range(S)) + "]", "",
            f"def cert : FunnelCert {n} {mw} {k} {p_rows} {d} {S} where",
            "  h := h", "  hh := by decide +kernel", "  As := Aseg", "  B := Bm", "  γ := γ",
            "  P := Pseg", "  P_symm := by decide +kernel", "  cs := rows", "  q := qs",
            "  hq := by decide +kernel", "  ρ := ρs", "  hρ := by decide +kernel",
            f"  v0 := {q(ec.v0)}", "  β := β", "  hβ := by decide +kernel",
            "  dissG := dissG",
            "  dissOK := by",
            "    intro i; fin_cases i",
            "    exacts [" + ", ".join(f"dissOK_{i}" for i in range(S)) + "]",
            "  bandG := bandG",
            "  bandOK := by",
            "    intro i; fin_cases i",
            "    exacts [" + ", ".join(f"bandOK_{i}" for i in range(S)) + "]",
            "  cont := by decide +kernel", "  margin := by decide +kernel", ""]
    emit_cert.modules = modules

    # literals and multipliers
    for li, lit in enumerate(lits):
        out.append(f"theorem lit{li} : ({lit} : ℝ) = {q(Fraction(lit))} := by norm_num")
    plan = link_plan(prob, fp)
    out.append("")
    eqn = len(m.equations_flat())
    enames = [f"e{i}" for i in range(eqn)]
    nb = m.n_bound
    bnames = [f"hb{i}" for i in range(nb)]
    lits_names = [f"lit{i}" for i in range(len(lits))]

    # per-segment Bernstein facts and enclosures
    out += ["/-! ### Per segment: reference range (Bernstein) and `cos` enclosure -/", ""]
    seg = ec.seg
    for i in range(S):
        a_i, b_i = h * i, h * (i + 1)
        for j, at in enumerate(fp.atoms):
            cs = refs[at.k][0]
            bc = seg.bern[i][j]
            lo_r, hi_r = min(bc), max(bc)
            c = (lo_r + hi_r) / 2
            r = (hi_r - lo_r) / 2
            bsh = [x - c for x in bc]
            rho = ec.rho[i][at.k]
            lo_g, hi_g = ec.gains[i][j]
            u, v = lo_r - rho, hi_r + rho
            nb_ = len(bsh) - 1
            out += [f"def bern_{i}_{j} : Fin {nb_ + 1} → ℚ := {vec(bsh)}",
                    f"theorem range_{i}_{j} {{t : ℝ}} (ht : t ∈ Icc ({_qr(a_i)}) ({_qr(b_i)})) :",
                    f"    GNC.PolynomialOrder.value ref{at.k} t ∈ Icc ({_qr(c)} - {_qr(r)}) ({_qr(c)} + {_qr(r)}) := by",
                    f"  have h := value_mem_of_bernstein (cs := ref{at.k}) (a := {q(a_i)}) (b := {q(b_i)})",
                    f"    (c := {q(c)}) (r := {q(r)}) (n := {nb_}) (bc := bern_{i}_{j}) (by decide +kernel)",
                    "    (by decide +kernel) (by decide +kernel) (by push_cast; exact ht)",
                    "  push_cast at h; exact h",
                    f"theorem enc_{i}_{j} : ∀ ξ ∈ Icc (({q(u)} : ℚ) : ℝ) (({q(v)} : ℚ) : ℝ),",
                    f"    (({q(lo_g)} : ℚ) : ℝ) ≤ Real.cos ξ ∧ Real.cos ξ ≤ (({q(hi_g)} : ℚ) : ℝ) :=",
                    "  cos_enclosure_rat (by decide +kernel)", ""]

    # the embedding lemma per segment
    def lc_line(mu, extra_coefs):
        parts = []
        for nm, cf in mu:
            parts.append(f"({q(cf)} : ℝ) * {nm}")
        parts += extra_coefs
        return " + ".join(parts) if parts else "0"

    yname = {at.k: m.var(fp.nominal_names[at.k]).lean for at in fp.atoms}
    for i in range(S):
        a_i, b_i = h * i, h * (i + 1)
        out += [f"theorem emb_{i} {{p : Params}} (hp : p.Bound) {{t : ℝ}} {{xs dxs : States}}",
                "    {us : Inputs} {ys : Algebraics} (he : Equations t p us xs dxs ys)",
                f"    (h1 : {_qr(a_i)} ≤ t) (h2 : t < {_qr(b_i)})",
                f"    (hband : ∀ l, |(fun j => (rows l j : ℝ)) ⬝ᵥ zvec xs t| < (ρs {i} l : ℝ)) :",
                f"    ∃ wt : Fin {k} → ℝ, (∀ j, 0 ≤ wt j) ∧ ∑ j, wt j = 1 ∧",
                f"      zdot dxs t = (∑ j, wt j • toReal (Aseg {i} j)) *ᵥ zvec xs t + toReal Bm *ᵥ dist us := by",
                "  obtain ⟨" + ", ".join(bnames) + "⟩ := hp",
                "  obtain ⟨" + ", ".join(enames) + "⟩ := he"]
        simp_set = ", ".join(bnames + lits_names)
        out.append(f"  simp only [{simp_set}] at {' '.join(enames)}")
        for kk in refs:
            out += [f"  have hv{kk} := ref{kk}_val t", f"  have hd{kk} := ref{kk}d_val t"]
        # algebraic definitions, in dependency order
        rules = []
        alg_lean = {v.symbol: v.lean for v in m.algebraics}
        for y in plan["order"]:
            ei = f"e{plan['defs'][y]}"
            if rules:
                out.append(f"  try simp only [{', '.join(rules)}] at {ei}")
            if y in plan["nominal_alg"]:
                kk = plan["nominal_alg"][y]
                out += [f"  have hy{kk} : ys.{alg_lean[y]} = GNC.PolynomialOrder.value ref{kk} t := by",
                        f"    rw [{ei}, ref{kk}_val]; ring"]
                rules.append(f"hy{kk}")
            else:
                rules.append(ei)
        dyn_names = [f"e{i}" for i in plan["dyn"]]
        out.append(f"  try simp only [{', '.join(rules)}] at {' '.join(dyn_names)}")
        if len(fp.atoms) != 1:
            raise NotImplementedError("one sin nonlinearity per model for now")
        at = fp.atoms[0]
        kk = at.k
        rho = ec.rho[i][kk]
        lo_g, hi_g = ec.gains[i][0]
        bc = seg.bern[i][0]
        lo_r, hi_r = min(bc), max(bc)
        c = (lo_r + hi_r) / 2
        r = (hi_r - lo_r) / 2
        u, v = lo_r - rho, hi_r + rho
        # the nominal equals the algebraic variable (from the equations)
        ys_k = yname[kk]
        out += [f"  have hr := range_{i}_0 (t := t) ⟨h1, h2.le⟩",
                f"  have hb := hband {kk}",
                f"  simp only [rows, zvec, dotProduct, Fin.sum_univ_succ, Fin.sum_univ_zero, Matrix.cons_val_zero,",
                "    Matrix.cons_val_succ, Matrix.cons_val_one, Matrix.head_cons, Rat.cast_one, Rat.cast_zero,",
                "    one_mul, zero_mul, add_zero, zero_add, ρs, Matrix.cons_val] at hb",
                f"  have hyk := hy{kk}",
                "  have hθ : xs." + st[kk] + f" ∈ Icc (({q(u)} : ℚ) : ℝ) (({q(v)} : ℚ) : ℝ) := by",
                "    push_cast at hr ⊢",
                "    constructor <;> linarith [abs_lt.mp hb, hr.1, hr.2]",
                f"  have hθs : GNC.PolynomialOrder.value ref{kk} t ∈ Icc (({q(u)} : ℚ) : ℝ) (({q(v)} : ℚ) : ℝ) := by",
                f"    push_cast at hr ⊢",
                f"    constructor <;> linarith [hr.1, hr.2, show (0 : ℝ) ≤ {_qr(rho)} by norm_num]",
                f"  obtain ⟨κ, hκ, hg0⟩ := sin_sub_gain hθ hθs enc_{i}_0 (by norm_num)",
                f"  have hlohi : (({q(lo_g)} : ℚ) : ℝ) < (({q(hi_g)} : ℚ) : ℝ) := by norm_num",
                f"  set lo : ℝ := (({q(lo_g)} : ℚ) : ℝ)",
                f"  set hi : ℝ := (({q(hi_g)} : ℚ) : ℝ)",
                "  refine ⟨![(hi - κ) / (hi - lo), (κ - lo) / (hi - lo)], ?_, ?_, ?_⟩",
                "  · intro j; fin_cases j",
                "    · exact div_nonneg (by linarith [hκ.2]) (by linarith)",
                "    · exact div_nonneg (by linarith [hκ.1]) (by linarith)",
                "  · simp only [Fin.sum_univ_two, Matrix.cons_val_zero, Matrix.cons_val_one,",
                "      Matrix.head_cons]",
                "    field_simp; ring",
                "  · have hwsum : (hi - κ) / (hi - lo) + (κ - lo) / (hi - lo) = 1 := by",
                "      field_simp; ring",
                "    have hwk : (hi - κ) / (hi - lo) * lo + (κ - lo) / (hi - lo) * hi = κ := by",
                "      field_simp; ring",
                "    funext c",
                "    fin_cases c <;>",
                "      simp only [zdot, zvec, dist, Aseg, A_" + f"{i}, Bm, Fin.sum_univ_two, toReal,",
                "        mulVec, dotProduct, Fin.sum_univ_succ, Fin.sum_univ_zero, Matrix.add_apply,",
                "        Matrix.smul_apply, Matrix.map_apply, Matrix.of_apply, Matrix.cons_val',",
                "        Matrix.cons_val_zero, Matrix.cons_val_succ, Matrix.cons_val_one, Matrix.head_cons,",
                "        Matrix.empty_val', Matrix.cons_val_fin_one, Pi.add_apply, smul_eq_mul,",
                "        Rat.coe_castHom, Fin.isValue, Fin.zero_eta, Fin.mk_one, fin_mk_ofNat, Matrix.zero_apply,",
                "        add_zero, Fin.succ_zero_eq_one, Fin.succ_one_eq_two, Matrix.cons_val] <;> push_cast"]
        # one bullet per component
        for comp in range(n):
            mu = plan["mult"][comp]
            # multipliers for the weight identities: μ_sum = -(A0 z)_comp, μ_κ = -a_comp z_k
            zterms = []
            for kk2, a in enumerate(fp.A0[comp]):
                if a != 0:
                    zterms.append(f"({q(a)} : ℝ) * ({zcomp(kk2, 'xs')})")
            a_c = at.a[comp]
            extra = []
            if zterms:
                extra.append(f"(-({' + '.join(zterms)})) * hwsum")
            if a_c != 0:
                extra.append(f"(-(({q(a_c)} : ℝ) * ({zcomp(kk, 'xs')}))) * hwk")
            out.append(f"    · linear_combination {lc_line(mu, extra)}")
        out.append("")

    # the final theorem
    bounds = [ec.bounds[nm] for nm in prob.spec.certify]
    out += [f"/-- Certified bounds on {', '.join(prob.spec.certify)} up to the horizon. -/",
            f"def bounds : Fin {len(bounds)} → ℚ := {vec(bounds)}", ""]
    # nominal algebraics and outputs from the equations
    nom_y = {kk: m.var(fp.nominal_names[kk]).lean for kk in refs}
    out += ["/-- The references named by `nominal` are the polynomials `ref_k`, and the certified",
            "outputs are error coordinates. -/",
            "theorem outputs {p : Params} (hp : p.Bound) {t : ℝ} {xs dxs : States} {us : Inputs}",
            "    {ys : Algebraics} (he : Equations t p us xs dxs ys) :"]
    concl = []
    for nm in prob.spec.certify:
        c = dict(fp.outputs)[nm]
        kk = c.index(1)
        concl.append(f"ys.{m.var(nm).lean} = zvec xs t {kk}")
    out.append("    " + " ∧ ".join(concl) + " := by")
    out += ["  obtain ⟨" + ", ".join(bnames) + "⟩ := hp",
            "  obtain ⟨" + ", ".join(enames) + "⟩ := he",
            f"  simp only [{', '.join(bnames + lits_names)}] at {' '.join(enames)}"]
    for kk in refs:
        out.append(f"  have hv{kk} := ref{kk}_val t")
    rules = []
    alg_lean = {v.symbol: v.lean for v in m.algebraics}
    for y in plan["order"]:
        ei = f"e{plan['defs'][y]}"
        if rules:
            out.append(f"  try simp only [{', '.join(rules)}] at {ei}")
        if y in plan["nominal_alg"]:
            kk = plan["nominal_alg"][y]
            out += [f"  have hy{kk} : ys.{alg_lean[y]} = GNC.PolynomialOrder.value ref{kk} t := by",
                    f"    rw [{ei}, ref{kk}_val]; ring"]
            rules.append(f"hy{kk}")
        else:
            rules.append(ei)
    goals = []
    for nm in prob.spec.certify:
        ei = f"e{plan['defs'][m.var(nm).symbol]}"
        goals.append(f"by rw [{ei}]; simp only [zvec, Matrix.cons_val_zero, Matrix.cons_val_one, "
                     "Matrix.head_cons, Matrix.cons_val_succ, Matrix.cons_val']; try ring")
    out.append("  exact ⟨" + ", ".join(goals) + "⟩" if len(goals) > 1 else f"  exact {goals[0]}")
    out.append("")

    ncert = len(prob.spec.certify)
    rows_of = [dict(fp.outputs)[nm].index(1) for nm in prob.spec.certify]
    hc = [f"hc{i}" for i in range(n)]
    out += ["theorem certified : Spec.Claim bounds := by",
            "  intro p u x y T hp hsol hadm hinit t ht htf",
            "  obtain ⟨dx, " + ", ".join(hc) + ", hder⟩ := hsol",
            "  set b := min T Spec.horizon with hbdef",
            "  have hbT : b ≤ T := min_le_left _ _",
            "  have hsub : Icc 0 b ⊆ Icc 0 T := Icc_subset_Icc le_rfl hbT",
            "  have hsubo : ∀ s ∈ Ico 0 b, s ∈ Ico 0 T := fun s hs => ⟨hs.1, lt_of_lt_of_le hs.2 hbT⟩",
            "  have hz_cont : ContinuousOn (fun s => zvec (x s) s) (Icc 0 b) := by",
            "    refine continuousOn_pi.mpr fun c => ?_",
            "    fin_cases c"]
    for i in range(n):
        if i in refs:
            out += [f"    · show ContinuousOn (fun s => (x s).{st[i]} - GNC.PolynomialOrder.value ref{i} s) (Icc 0 b)",
                    f"      exact (hc{i}.mono hsub).sub (continuous_iff_continuousAt.mpr",
                    f"        fun s => (ref{i}_deriv s).continuousAt).continuousOn"]
        else:
            out += [f"    · show ContinuousOn (fun s => (x s).{st[i]} - {_qr(Fraction(fp.nominal[i]))}) (Icc 0 b)",
                    f"      exact (hc{i}.mono hsub).sub continuousOn_const"]
    out += ["  have hz_der : ∀ s ∈ Ico 0 b, HasDerivWithinAt (fun s => zvec (x s) s) (zdot (dx s) s)",
            "      (Ici s) s := by",
            "    intro s hs",
            "    obtain ⟨" + ", ".join(f"hd{i}" for i in range(n)) + ", -⟩ := hder s (hsubo s hs)",
            "    rw [hasDerivWithinAt_pi]",
            "    intro c",
            "    fin_cases c"]
    for i in range(n):
        if i in refs:
            out += [f"    · show HasDerivWithinAt (fun s => (x s).{st[i]} - GNC.PolynomialOrder.value ref{i} s)",
                    f"        ((dx s).{st[i]} - GNC.PolynomialOrder.value ref{i}d s) (Ici s) s",
                    f"      exact hd{i}.sub (ref{i}_deriv s).hasDerivWithinAt"]
        else:
            out += [f"    · show HasDerivWithinAt (fun s => (x s).{st[i]} - {_qr(Fraction(fp.nominal[i]))})",
                    f"        ((dx s).{st[i]}) (Ici s) s",
                    f"      exact (hd{i}.sub_const _)"]
    out += [f"  have hemb : ∀ i : Fin {S}, ∀ s ∈ Ico 0 b, 0 + ((i : ℕ) : ℝ) * (cert.h : ℝ) ≤ s →",
            "      s < 0 + (((i : ℕ) : ℝ) + 1) * (cert.h : ℝ) →",
            "      (∀ l, |(fun j => (cert.cs l j : ℝ)) ⬝ᵥ zvec (x s) s| < (cert.ρ i l : ℝ)) →",
            f"      ∃ wt : Fin {k} → ℝ, (∀ j, 0 ≤ wt j) ∧ ∑ j, wt j = 1 ∧",
            "        zdot (dx s) s = (∑ j, wt j • toReal (cert.As i j)) *ᵥ zvec (x s) s",
            "          + toReal cert.B *ᵥ dist (u s) := by",
            "    intro i s hs h1 h2 hband",
            "    obtain ⟨-, " + ", ".join("-" for _ in range(n - 1)) + ", he⟩ := hder s (hsubo s hs)",
            "    simp only [cert, h] at h1 h2",
            "    fin_cases i"]
    for i in range(S):
        out += [f"    · exact emb_{i} hp he (by push_cast at h1 ⊢; linarith) (by push_cast at h2 ⊢; linarith) hband"]
    wb = fp.w_bounds
    out += ["  have hw : ∀ s ∈ Ico 0 b, ∑ j, (cert.γ j : ℝ) * (dist (u s) j * dist (u s) j) ≤ cert.β := by",
            "    intro s hs",
            "    have ha := hadm s (hsubo s hs)"]
    if mw == 1:
        out += [f"    have hsq : (u s).{m.var(fp.w_names[0]).lean} * (u s).{m.var(fp.w_names[0]).lean} ≤ {_qr(wb[0] ** 2)} := by",
                "      have := abs_le.mp ha; nlinarith",
                "    simp only [cert, γ, β, dist, Fin.sum_univ_succ, Fin.sum_univ_zero, Matrix.cons_val_zero, add_zero]",
                "    push_cast",
                f"    nlinarith [hsq]"]
    else:
        raise NotImplementedError("several disturbance channels")
    init_rules = ", ".join(f"i{i}" for i in range(n))
    out += ["  have h0 : quad (toReal (cert.P ⟨0, by norm_num⟩ ⟨0, by norm_num⟩)) (zvec (x 0) 0) ≤ (cert.v0 : ℝ) := by",
            f"    obtain ⟨{init_rules}⟩ := hinit",
            "    have hz : zvec (x 0) 0 = 0 := by",
            "      funext c",
            "      fin_cases c <;> simp [zvec, " + init_rules + ", " +
            ", ".join(f"ref{i}_val" for i in refs) + "]",
            "    rw [hz]",
            "    simp [quad, cert]"]
    out += ["  have htb : t ∈ Icc 0 b := ⟨ht.1, le_min ht.2.le htf⟩",
            f"  have htS : t ≤ 0 + ({S} : ℕ) * (cert.h : ℝ) := by",
            "    simp only [cert, h, Spec.horizon] at htf ⊢; push_cast; linarith",
            "  obtain ⟨-, " + ", ".join("-" for _ in range(n - 1)) + ", he⟩ := hder t ht",
            "  have hout := outputs hp he"]
    parts = []
    for oi, (nm, row) in enumerate(zip(prob.spec.certify, rows_of)):
        out += [f"  have hb{oi} := cert.output_bound (by norm_num) hz_cont hz_der hemb hw h0 {row}",
                f"    (bnd := bounds {oi}) (by decide +kernel) (by decide +kernel) t htb htS",
                f"  simp only [cert, rows, dotProduct, Fin.sum_univ_succ, Fin.sum_univ_zero,",
                "    Matrix.cons_val_zero, Matrix.cons_val_one, Matrix.head_cons, Matrix.cons_val_succ,",
                "    Matrix.cons_val', Rat.cast_one, Rat.cast_zero, one_mul, zero_mul, add_zero,",
                f"    zero_add] at hb{oi}"]
    if ncert == 1:
        out += ["  rw [hout]; exact hb0"]
    else:
        out += ["  obtain ⟨" + ", ".join(f"ho{i}" for i in range(ncert)) + "⟩ := hout",
                "  exact ⟨" + ", ".join(f"by rw [ho{i}]; exact hb{i}" for i in range(ncert)) + "⟩"]
    out += ["", f"end {ns}.Funnel", ""]
    return "\n".join(out)


