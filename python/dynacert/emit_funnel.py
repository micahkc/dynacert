def generate(prob, segments: int = 16, degree: int = 3, verbose=print):
    """Synthesize and write `Model.lean`, `Spec.lean`, `FunnelCert.lean` (no build)."""
    from . import funnel as F
    fp = F.extract(prob)
    verbose(f"funnel: {len(fp.atoms)} sin nonlinearity, horizon {fp.horizon}, "
            f"{segments} segments, P(t) of degree {degree}")
    syn = F.synthesize(fp, S=segments, R=degree, verbose=verbose,
                       weights=[1.0 if any(c[k] == 1 for _, c in fp.outputs) else 0.05
                                for k in range(len(fp.xs))])
    ec = F.exact_certificate(fp, syn, verbose=verbose)
    verbose("funnel: exact certificate, bounds " +
            ", ".join(f"|{n}| ≤ {float(b):.4g}" for n, b in ec.bounds.items()))
    out = prob.cert_dir
    out.mkdir(parents=True, exist_ok=True)
    (out / "Model.lean").write_text(prob.lean_src)
    (out / "Spec.lean").write_text(emit_spec(prob, fp))
    (out / "FunnelCert.lean").write_text(emit_cert(prob, fp, ec))
    for f in out.glob("FunnelSeg*.lean"):
        f.unlink()
    for name, src in emit_cert.modules.items():
        (out / name).write_text(src)
    return fp, ec, out


MEMORY_MAX = "10G"


def build_capped(target: str, root, memory: str = MEMORY_MAX):
    """`lake build target` in its own systemd scope with a memory cap, so an oversized kernel
    check is killed alone instead of exhausting the machine."""
    import shutil
    import subprocess
    from . import pipeline
    cmd = ["lake", "build", target]
    if shutil.which("systemd-run"):
        cmd = ["systemd-run", "--user", "--scope", "--quiet", "-p", f"MemoryMax={memory}",
               "-p", "MemorySwapMax=0"] + cmd
    r = subprocess.run(cmd, cwd=root, capture_output=True, text=True)
    if r.returncode != 0:
        raise pipeline.CertError(f"lake build {target} failed ({r.returncode}; memory cap "
                                 f"{memory}):\n{r.stdout[-3000:]}\n{r.stderr[-2000:]}")


def run(prob, segments: int = 16, degree: int = 3, verbose=print) -> dict:
    import json
    from . import pipeline
    fp, ec, out = generate(prob, segments, degree, verbose)
    mod = f"Certs.{prob.model.ns}.FunnelCert"
    # one module at a time, under a memory cap: the Gram checks are heavy for the kernel
    segs = sorted(int(f.stem[len("FunnelSeg"):]) for f in out.glob("FunnelSeg*.lean"))
    for target in ([f"Certs.{prob.model.ns}.FunnelBase"] +
                   [f"Certs.{prob.model.ns}.FunnelSeg{i}" for i in segs] + [mod]):
        verbose(f"lean: lake build {target}")
        build_capped(target, prob.root)
    ax = pipeline.axioms(mod, f"{prob.model.ns}.Funnel.certified", root=prob.root)
    if not ax <= pipeline.ALLOWED_AXIOMS:
        raise pipeline.CertError(f"disallowed axioms: {ax - pipeline.ALLOWED_AXIOMS}")
    side = {"model": prob.model.name, "method": "funnel-sos",
            "theorem": f"{prob.model.ns}.Funnel.certified", "axioms": sorted(ax),
            "horizon": q(fp.horizon), "segments": ec.S, "degree": ec.R,
            "bounds": {n: q(b) for n, b in ec.bounds.items()},
            "segment_bounds": {n: [q(x) for x in _segment_bounds(fp, ec, n)] for n in ec.bounds}}
    (out / "funnel.json").write_text(json.dumps(side, indent=1))
    return {"dir": str(out), "sidecar": side}


def _segment_bounds(fp, ec, name):
    import math
    c = dict(fp.outputs)[name]
    k = c.index(1)
    return [Fraction(math.isqrt(int(ec.q[i][k] * (ec.v0 + ec.beta * ec.h * (i + 1)) * 10**12)) + 1,
                     10**6) for i in range(ec.S)]
