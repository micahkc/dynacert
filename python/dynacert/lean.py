"""Lean source emission helpers (rationals, matrices, identifiers)."""

from __future__ import annotations

import re
from fractions import Fraction

# Must match the identifier quoting in rumoca's lean-dae template (`ident` macro).
LEAN_KEYWORDS = {
    "at", "by", "do", "else", "end", "fun", "from", "have", "if", "in", "let", "match", "then",
    "show", "with", "where", "for", "theorem", "def", "structure", "namespace", "section",
    "open", "import", "instance", "class", "variable", "universe", "example", "abbrev",
    "deriving", "mut", "return", "try", "catch", "finally", "unless", "calc", "suffices",
    "obtain", "Type", "Prop", "Sort", "local", "private", "protected", "noncomputable",
    "partial", "unsafe", "macro", "syntax", "notation", "λ", "Π", "Σ", "∀", "∃",
}


def ident(name: str) -> str:
    """Quote a Modelica name the same way rumoca's lean-dae target does."""
    if (name in LEAN_KEYWORDS or re.search(r"[.\[\]' $(,\-]", name) or name[:1].isdigit()):
        return f"«{name}»"
    return name


def sanitize(name: str) -> str:
    """rumoca's `sanitize` filter for model names (namespace / file name)."""
    return "".join(c if (c.isalnum() or c == "_") else "_" for c in name if c != "]")


def q(x) -> str:
    """A rational literal, valid at any numeric type (`ℚ`, `ℝ`)."""
    x = Fraction(x)
    if x.denominator == 1:
        return str(x.numerator)
    return f"{x.numerator}/{x.denominator}"


def qp(x) -> str:
    """Parenthesized rational literal."""
    s = q(x)
    return f"({s})" if ("/" in s or s.startswith("-")) else s


def mat(X) -> str:
    if not X or not X[0]:
        rows, cols = len(X), (len(X[0]) if X else 0)
        return f"(0 : Matrix (Fin {rows}) (Fin {cols}) ℚ)"
    return "!![" + "; ".join(", ".join(q(v) for v in r) for r in X) + "]"


def vec(v) -> str:
    return "![" + ", ".join(q(x) for x in v) + "]"


def sum_witness(L, d, n: int, m: int) -> tuple[str, str]:
    """Lean terms `(L, d)` for a witness indexed by `Fin n ⊕ Fin m`."""
    blk = lambda r0, r1, c0, c1: [row[c0:c1] for row in L[r0:r1]]
    Lt = (f"fromBlocks {mat(blk(0, n, 0, n))} {mat(blk(0, n, n, n + m))}\n"
          f"      {mat(blk(n, n + m, 0, n))} {mat(blk(n, n + m, n, n + m))}")
    return Lt, f"Sum.elim {vec(d[:n])} {vec(d[n:])}"


def header(title: str, generator: str) -> list[str]:
    return [
        "/-!",
        f"# {title}",
        "",
        f"GENERATED by `{generator}`; do not edit. The generator is untrusted: every fact",
        "below is checked by the Lean kernel (`decide +kernel`), with no `native_decide`.",
        "-/",
        "",
    ]


def sympy_to_lean(expr, names: dict) -> str:
    """Render a sympy rational/polynomial expression as a Lean `ℝ` term.

    `names` maps sympy symbols to Lean terms (e.g. a parameter symbol to `p.c`).
    Only `+ * / ^`(natural), rationals and mapped symbols are supported.
    """
    import sympy as sp

    def go(e) -> str:
        if e.is_Rational:
            return f"({q(Fraction(int(e.p), int(e.q)))} : ℝ)"
        if e.is_Symbol:
            if e not in names:
                raise ValueError(f"unmapped symbol {e}")
            return names[e]
        if e.is_Add:
            return "(" + " + ".join(go(a) for a in e.args) + ")"
        if e.is_Mul:
            num, den = sp.fraction(e)
            if den != 1:
                return f"({go(num)} / {go(den)})"
            return "(" + " * ".join(go(a) for a in e.args) + ")"
        if e.is_Pow and e.exp.is_Integer:
            if e.exp > 0:
                return f"({go(e.base)} ^ {int(e.exp)})"
            return f"(1 / ({go(e.base)} ^ {int(-e.exp)}))"
        raise ValueError(f"cannot render {e} in Lean")

    return go(sp.sympify(expr))
